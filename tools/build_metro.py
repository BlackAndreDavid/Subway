#!/usr/bin/env python3
"""Compile curated real topology to Godot data and an original raster line-map.
Needs Pillow only to rebuild the PNG. Runtime/CI can use committed PNG without Pillow.
"""
import json,sys
from pathlib import Path
root=Path(__file__).resolve().parents[1]
d=json.loads((root/'assets/maps/shanghai_metro.json').read_text())
# Correct ordered selected-stop topology, intentionally omit intermediate minor stops.
for line in d['lines']:
 if line['id']=='7':line['stations']=[i for i in line['stations'] if d['stations'][i]['name']!='龙华']
(root/'assets/maps/shanghai_metro.json').write_text(json.dumps(d,ensure_ascii=False,indent=2)+'\n')
def gd(value):
 if isinstance(value,dict):return '{'+','.join(json.dumps(k,ensure_ascii=False)+':'+gd(v) for k,v in value.items())+'}'
 if isinstance(value,list):return '['+','.join(gd(x) for x in value)+']'
 return json.dumps(value,ensure_ascii=False)
rows=[]
for s in d['stations']:
 t=dict(s);pos=t.pop('pos');r=gd(t);rows.append(r[:-1]+',"pos":Vector2(%d,%d)}'%tuple(pos))
(root/'scripts/metro_data.gd').write_text('extends RefCounted\n# Generated by tools/build_metro.py from the curated source JSON.\nconst STATIONS = [\n\t'+',\n\t'.join(rows)+'\n]\nconst LINES = '+gd(d['lines'])+'\nconst CANVAS = Vector2(1840,1440)\n')
if "--data-only" in sys.argv:
 print("Godot table generated from curated JSON (PNG unchanged).")
 raise SystemExit(0)
try:
 from PIL import Image,ImageDraw,ImageFont
except ImportError:
 print('Godot table generated. Install Pillow to rebuild the map PNG.');raise SystemExit(0)
im=Image.new('RGB',tuple(d['canvas']),'#10242e');draw=ImageDraw.Draw(im)
for x in range(0,1840,80):draw.line((x,0,x,1440),fill='#162e38')
for y in range(0,1440,80):draw.line((0,y,1840,y),fill='#162e38')
# Stylized Huangpu waterway, for geographic orientation only.
river=[(1360,0),(1350,260),(1245,460),(1105,550),(1075,690),(1130,800),(1110,900),(1015,1020),(945,1200),(925,1440)]
draw.line(river,fill='#193b4a',width=45,joint='curve')
for line in d['lines']:
 pts=[tuple(d['stations'][i]['pos']) for i in line['stations']]
 draw.line(pts,fill='#0a1b24',width=13,joint='curve')
 draw.line(pts,fill='#'+line['color'],width=7,joint='curve')
for station in d['stations']:
 x,y=station['pos'];r=5 if len(station['lines'])==1 else 8
 draw.ellipse((x-r,y-r,x+r,y+r),fill='#d5e4db',outline='#142a35',width=2)
im.save(root/'assets/maps/shanghai_metro.png')
# Separate print reference with all labels; runtime layers text for legibility.
font=ImageFont.truetype(str(root/'assets/fonts/subway_cjk.otf'),16)
for station in d['stations']:
 x,y=station['pos'];draw.text((x+10,y-21),station['name'],font=font,fill='#e0e8db',stroke_width=2,stroke_fill='#10242e')
im.save(root/'assets/maps/shanghai_metro_reference.png')
print('Generated Godot table and two original Shanghai metro PNGs:',len(d['stations']),'nodes')
