#!/usr/bin/env python3
"""Compile the ten authored obstacle layouts into an export-safe Godot resource."""
from pathlib import Path
import json

ROOT=Path(__file__).resolve().parents[1]
def compile_layouts():
    data=json.loads((ROOT/'assets/rooms/layouts.json').read_text())
    assert len(data['layouts'])==10
    for layout in data['layouts']:
        rows=layout['rows']
        assert len(rows)==data['rows'] and all(len(row)==data['columns'] for row in rows)
        free={(x,y) for y,row in enumerate(rows) for x,c in enumerate(row) if c=='.'}
        assert free and any('#' in row for row in rows)
        seen={next(iter(free))}; queue=list(seen)
        for x,y in queue:
            for p in [(x-1,y),(x+1,y),(x,y-1),(x,y+1)]:
                if p in free and p not in seen:seen.add(p);queue.append(p)
        assert seen==free,layout['id']+' disconnects the walkable floor'
        assert all((x,0) in free and (x,8) in free for x in range(15))
        assert all((0,y) in free and (14,y) in free for y in range(9))
    return 'extends RefCounted\n# Generated by tools/generate_room_layouts.py from assets/rooms/layouts.json.\nconst COLUMNS=15\nconst ROWS=9\nconst LAYOUTS='+json.dumps(data['layouts'],ensure_ascii=False,indent=2)+'\n'
if __name__=='__main__':
    (ROOT/'scripts/room_layout_data.gd').write_text(compile_layouts())
    print('Compiled ten connected obstacle layouts.')
